class RefereeResultTests(TournamentAPITestCase):
    def setUp(self):
        self.admin = self.make_user("admin.ref@example.com", "admin")
        self.organizer = self.make_user("org.ref@example.com", "organizer")

        self.venue = Venues.objects.create(venue_name="Central", created_at=timezone.now())
        self.tournament = Tournaments.objects.create(
            name="Ref Cup",
            organized_by=self.organizer,
            start_date=date(2026, 12, 1),
            end_date=date(2026, 12, 31),
        )

        self.referee_record = Referees.objects.create(
            name="QA Referee",
            email="qa-referee@example.com",
            created_at=timezone.now(),
        )
        self.referee = self.make_user(
            "ref.assigned@example.com",
            "referee",
            referee=self.referee_record,
        )

        self.home = Teams.objects.create(team_name="Home XI", created_at=timezone.now())
        self.away = Teams.objects.create(team_name="Away XI", created_at=timezone.now())
        for team in (self.home, self.away):
            TournamentTeams.objects.create(
                tournament=self.tournament,
                team=team,
                registered_at=timezone.now(),
            )

        self.assigned_match = Matches.objects.create(
            tournament=self.tournament,
            venue=self.venue,
            match_date=date(2026, 12, 10),
            round="Quarterfinal",
        )
        self.unassigned_match = Matches.objects.create(
            tournament=self.tournament,
            venue=self.venue,
            match_date=date(2026, 12, 12),
            round="Semifinal",
        )

        MatchTeams.objects.create(match=self.assigned_match, team=self.home, team_side="Home")
        MatchTeams.objects.create(match=self.assigned_match, team=self.away, team_side="Away")
        MatchTeams.objects.create(match=self.unassigned_match, team=self.home, team_side="Home")
        MatchTeams.objects.create(match=self.unassigned_match, team=self.away, team_side="Away")

        MatchReferees.objects.create(match=self.assigned_match, referee=self.referee_record)

    def test_referee_submits_result_for_assigned_match(self):
        client = self.login_as("ref.assigned@example.com")

        response = client.post(
            "/api/results/",
            {
                "match": self.assigned_match.match_id,
                "team1_score": 3,
                "team2_score": 1,
            },
            format="json",
        )

        self.assertEqual(response.status_code, status.HTTP_201_CREATED)
        self.assertEqual(response.data["winner_team"], self.home.team_id)

    def test_referee_cannot_submit_for_unassigned_match(self):
        client = self.login_as("ref.assigned@example.com")

        response = client.post(
            "/api/results/",
            {
                "match": self.unassigned_match.match_id,
                "team1_score": 1,
                "team2_score": 0,
            },
            format="json",
        )
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_duplicate_result_rejected(self):
        Results.objects.create(match=self.assigned_match, team1_score=1, team2_score=1)
        client = self.login_as("ref.assigned@example.com")

        response = client.post(
            "/api/results/",
            {
                "match": self.assigned_match.match_id,
                "team1_score": 2,
                "team2_score": 0,
            },
            format="json",
        )
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_standings_recompute_and_reset(self):
        client = self.login_as("ref.assigned@example.com")

        response = client.post(
            "/api/results/",
            {
                "match": self.assigned_match.match_id,
                "team1_score": 3,
                "team2_score": 1,
            },
            format="json",
        )
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

        listing = client.get("/api/tournament-standings/")
        rows = {
            row["team"]: row
            for row in listing.data
            if row["tournament"] == self.tournament.tournament_id
        }

        home_row = rows[self.home.team_id]
        away_row = rows[self.away.team_id]

        self.assertEqual(home_row["played"], 1)
        self.assertEqual(home_row["won"], 1)
        self.assertEqual(home_row["goals_for"], 3)
        self.assertEqual(home_row["goals_against"], 1)
        self.assertEqual(home_row["points"], 3)
        self.assertEqual(away_row["played"], 1)
        self.assertEqual(away_row["lost"], 1)
        self.assertEqual(away_row["points"], 0)

        # Deleting the only result must rebuild (not accumulate).
        result_row = Results.objects.get(match=self.assigned_match)

        admin_client = self.login_as("admin.ref@example.com")
        deleted = admin_client.delete(f"/api/results/{result_row.result_id}/")
        self.assertEqual(deleted.status_code, status.HTTP_204_NO_CONTENT)

        after = admin_client.get("/api/tournament-standings/").data
        rebuilt = {
            row["team"]: row
            for row in after
            if row["tournament"] == self.tournament.tournament_id
        }
        self.assertEqual(rebuilt[self.home.team_id]["played"], 0)


