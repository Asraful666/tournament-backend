class AuthFlowTests(TournamentAPITestCase):
    def test_signup_creates_viewer_with_hashed_password(self):
        response = self.client.post(
            "/api/auth/signup/",
            {
                "name": "New User",
                "email": "signup.success@example.com",
                "password": TEST_PASSWORD,
            },
            format="json",
        )

        self.assertEqual(response.status_code, status.HTTP_201_CREATED)
        self.assertEqual(response.data["user"]["role"], "viewer")

        user = Users.objects.get(email="signup.success@example.com")
        self.assertEqual(user.role, "viewer")
        self.assertFalse(user.password.startswith("Suite"))
        # created_at must be stamped server-side (regression).
        self.assertIsNotNone(user.created_at)

    def test_signup_rejects_duplicate_email(self):
        self.make_user("dup@example.com", "viewer")

        response = self.client.post(
            "/api/auth/signup/",
            {
                "name": "Dup",
                "email": "DUP@example.com",
                "password": TEST_PASSWORD,
            },
            format="json",
        )

        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_signup_weak_password_rejected(self):
        response = self.client.post(
            "/api/auth/signup/",
            {
                "name": "Weak PW",
                "email": "weak@example.com",
                "password": "password1234",
            },
            format="json",
        )

        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)
        self.assertTrue(response.data, "Expected a validation error body")

    def test_login_logout_me_roundtrip(self):
        self.make_user("flow@example.com", "organizer")

        wrong = self.client.post(
            "/api/auth/login/",
            {"email": "flow@example.com", "password": "definitely-wrong"},
            format="json",
        )
        self.assertEqual(wrong.status_code, status.HTTP_401_UNAUTHORIZED)

        client = self.login_as("flow@example.com")

        me = client.get("/api/auth/me/")
        self.assertEqual(me.status_code, status.HTTP_200_OK)
        self.assertEqual(me.data["role"], "organizer")

        logout = client.post("/api/auth/logout/")
        self.assertEqual(logout.status_code, status.HTTP_200_OK)

        me_after = client.get("/api/auth/me/")
        self.assertEqual(me_after.status_code, status.HTTP_401_UNAUTHORIZED)


