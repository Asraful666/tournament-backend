class ViewerReadOnlyTests(TournamentAPITestCase):
    def setUp(self):
        # Seed one team so detail-write probes have a real 404-free target.
        self.team = Teams.objects.create(team_name="Probe", created_at=timezone.now())
        self.viewer = self.make_user("viewer.test@example.com", "viewer")
        self.client = self.login_as("viewer.test@example.com")

    def test_viewer_can_read_everything(self):
        for url in (
            "/api/teams/",
            "/api/venues/",
            "/api/matches/",
            "/api/results/",
            "/api/tournament-standings/",
        ):
            response = self.client.get(url)
            self.assertEqual(response.status_code, status.HTTP_200_OK, url)

    def test_viewer_cannot_write_anything(self):
        cases = [
            ("POST", "/api/venues/", {"venue_name": "X", "location": "y", "capacity": 1}),
            ("PATCH", f"/api/teams/{self.team.team_id}/", {"team_name": "X"}),
            ("POST", "/api/tournaments/", {"name": "X"}),
            ("POST", "/api/users/", {"name": "X", "email": "x@example.com"}),
        ]

        for method, url, payload in cases:
            if method == "DELETE" and payload is None:
                continue

            response = getattr(self.client, method.lower())(
                url,
                payload,
                format="json",
            )

            self.assertEqual(
                response.status_code,
                status.HTTP_403_FORBIDDEN,
                f"{method} {url} returned {response.status_code}",
            )

    def test_viewer_cannot_list_users(self):
        response = self.client.get("/api/users/")
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)


