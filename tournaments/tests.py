"""
Automated test suite for the tournament API.

Schema note: every model here is `managed = False` (generated by
`inspectdb` from an existing MySQL database) and the app ships no
migrations, so Django does NOT create the app tables in the test
database. setUpModule() therefore builds them with the schema editor —
the standard workaround for unmanaged/inspect-backed projects.

Tests run against `test_tournament_management`; between tests every
table is truncated via TournamentAPITestCase.tearDown, so the real
database is never touched.
"""

from datetime import date, timedelta

from django.contrib.auth.hashers import make_password
from django.db import connection
from django.utils import timezone
from django.test import TransactionTestCase
from rest_framework import status
from rest_framework.test import APIClient

from .models import (
    MatchReferees,
    MatchTeams,
    Matches,
    Players,
    Referees,
    Results,
    Teams,
    TournamentStandings,
    TournamentTeams,
    Tournaments,
    Users,
    Venues,
)

from . import views as _views

# Unit tests would otherwise trip the login/signup throttles (the DRF
# cache counts across tests). Only affects the test process.
_views.AuthLoginAPIView.throttle_classes = []
_views.SignupAPIView.throttle_classes = []

TEST_PASSWORD = "Suite-Strong!2026"


def setUpModule():
    """Build the unmanaged tables in the fresh test database."""
    existing = set(connection.introspection.table_names())
    missing = [
        model
        for model in (
            Venues,
            Referees,
            Teams,
            Players,
            Tournaments,
            Matches,
            TournamentTeams,
            TournamentStandings,
            MatchTeams,
            MatchReferees,
            Results,
            Users,
        )
        if model._meta.db_table not in existing
    ]

    if not missing:
        return

    with connection.cursor() as cursor:
        cursor.execute("SET FOREIGN_KEY_CHECKS=0")

    try:
        with connection.schema_editor() as schema:
            for model in missing:
                schema.create_model(model)
    finally:
        with connection.cursor() as cursor:
            cursor.execute("SET FOREIGN_KEY_CHECKS=1")


class TournamentAPITestCase(TransactionTestCase):
    """Shared helpers: writes are truncated after every test."""

    def tearDown(self):
        table_models = (
            Venues,
            Referees,
            Teams,
            Players,
            Tournaments,
            Matches,
            TournamentTeams,
            TournamentStandings,
            MatchTeams,
            MatchReferees,
            Results,
            Users,
        )
        table_names = set(connection.introspection.table_names())

        with connection.cursor() as cursor:
            cursor.execute("SET FOREIGN_KEY_CHECKS=0")
            try:
                for model in table_models:
                    if model._meta.db_table in table_names:
                        cursor.execute(f"TRUNCATE TABLE `{model._meta.db_table}`")
            finally:
                cursor.execute("SET FOREIGN_KEY_CHECKS=1")

        super().tearDown()

    # --------------------------------------------------------------
    # Factories
    # --------------------------------------------------------------

    def make_user(self, email, role, name="QA User", **links):
        """Password is always hashed through the same code path as prod."""
        return Users.objects.create(
            name=name,
            email=email,
            role=role,
            password=make_password(TEST_PASSWORD),
            created_at=timezone.now(),
            **links,
        )

    def login_as(self, email, password=TEST_PASSWORD):
        """Fresh client authenticated through the real login endpoint."""
        client = APIClient(enforce_csrf_checks=False)

        response = client.post(
            "/api/auth/login/",
            {"email": email, "password": password},
            format="json",
        )

        self.assertEqual(
            response.status_code,
            status.HTTP_200_OK,
            f"Failed login for {email}: {getattr(response, 'data', '')}",
        )

        return client


